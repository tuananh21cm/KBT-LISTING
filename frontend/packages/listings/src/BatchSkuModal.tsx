import { useEffect, useMemo, useState } from 'react';
import { Input, Radio, Select, Typography } from 'antd';
import { Modal } from '@drop/ui';
import type { ListingVariationRow } from './productFormTypes';
import {
  DEFAULT_SKU_RULE_CONFIG,
  SKU_RULE_SEGMENT_OPTIONS,
  generateBatchSkus,
  type SkuBatchMode,
  type SkuBatchRuleConfig,
  type SkuRuleSegment,
} from './skuBatchUtils';

const { Text } = Typography;

interface BatchSkuModalProps {
  open: boolean;
  variations: ListingVariationRow[];
  externalProductId?: string;
  onCancel: () => void;
  onApply: (skus: string[]) => void;
}

const RULE_SELECT_OPTIONS = SKU_RULE_SEGMENT_OPTIONS;

function RuleSelect({
  label,
  value,
  customValue,
  onChange,
  onCustomChange,
}: {
  label: string;
  value: SkuRuleSegment;
  customValue?: string;
  onChange: (v: SkuRuleSegment) => void;
  onCustomChange: (v: string) => void;
}) {
  return (
    <div className="fs-batch-sku-rule-row">
      <Text className="fs-batch-sku-rule-label">{label}</Text>
      <Select
        size="small"
        style={{ width: '100%' }}
        value={value}
        options={RULE_SELECT_OPTIONS}
        onChange={onChange}
      />
      {value === 'custom' && (
        <Input
          size="small"
          placeholder="Nhập giá trị"
          value={customValue}
          onChange={(e) => onCustomChange(e.target.value)}
        />
      )}
    </div>
  );
}

export function BatchSkuModal({
  open,
  variations,
  externalProductId,
  onCancel,
  onApply,
}: BatchSkuModalProps) {
  const [mode, setMode] = useState<SkuBatchMode>('rules');
  const [rules, setRules] = useState<SkuBatchRuleConfig>(DEFAULT_SKU_RULE_CONFIG);

  useEffect(() => {
    if (!open) return;
    setMode('rules');
    setRules(DEFAULT_SKU_RULE_CONFIG);
  }, [open]);

  const previewSkus = useMemo(
    () => generateBatchSkus(variations, mode, rules, externalProductId),
    [variations, mode, rules, externalProductId],
  );

  const handleApply = () => {
    onApply(previewSkus);
    onCancel();
  };

  return (
    <Modal
      title="Bulk Edit Shop SKU"
      open={open}
      onCancel={onCancel}
      onOk={handleApply}
      okText="Save"
      cancelText="Cancel"
      width={720}
      destroyOnHidden
    >
      <Radio.Group
        value={mode}
        onChange={(e) => setMode(e.target.value as SkuBatchMode)}
        style={{ marginBottom: 16 }}
      >
        <Radio value="rules">Generated By Rules</Radio>
        <Radio value="random">Random (4seller)</Radio>
      </Radio.Group>

      <div className="fs-batch-sku-body">
        <div className="fs-batch-sku-config">
          {mode === 'rules' ? (
            <>
              <RuleSelect
                label="Prefix"
                value={rules.prefix}
                customValue={rules.prefixCustom}
                onChange={(prefix) => setRules((r) => ({ ...r, prefix }))}
                onCustomChange={(prefixCustom) => setRules((r) => ({ ...r, prefixCustom }))}
              />
              <RuleSelect
                label="Middle code"
                value={rules.middle}
                customValue={rules.middleCustom}
                onChange={(middle) => setRules((r) => ({ ...r, middle }))}
                onCustomChange={(middleCustom) => setRules((r) => ({ ...r, middleCustom }))}
              />
              <RuleSelect
                label="Suffix"
                value={rules.suffix}
                customValue={rules.suffixCustom}
                onChange={(suffix) => setRules((r) => ({ ...r, suffix }))}
                onCustomChange={(suffixCustom) => setRules((r) => ({ ...r, suffixCustom }))}
              />
            </>
          ) : (
            <Text type="secondary">
              Mỗi variant nhận mã dạng{' '}
              <Text code>
                {externalProductId?.replace(/\D/g, '').slice(0, 9).padStart(9, '0') ||
                  '102918554'}
                -I9chw29tlxsv
              </Text>
              . Phần số lấy từ External Product ID (9 chữ số), phần sau là chuỗi ngẫu nhiên 12 ký
              tự — mỗi variant một mã riêng.
            </Text>
          )}
        </div>

        <div className="fs-batch-sku-preview">
          <Text type="secondary" style={{ display: 'block', marginBottom: 8 }}>
            Preview
          </Text>
          {previewSkus.length === 0 ? (
            <Text type="secondary">Chưa có variant.</Text>
          ) : (
            <ul className="fs-batch-sku-preview-list">
              {previewSkus.map((sku, i) => (
                <li key={`${i}-${sku}`}>
                  <Text>{sku}</Text>
                </li>
              ))}
            </ul>
          )}
        </div>
      </div>
    </Modal>
  );
}
